def get_all_courses():
    """Return all available courses."""
    return courses


def get_course_by_id(course_id):
    """Find a course using its ID."""
    for course in courses:
        if course["id"] == course_id:
            return course

    return None


def get_courses_by_skill(skill):
    """Return courses related to a particular skill."""
    result = []

    for course in courses:
        if course["skill"].lower() == skill.lower():
            result.append(course)

    return result


def get_courses_by_role(role):
    """Return courses suitable for a target role."""
    result = []

    for course in courses:
        for target_role in course["target_roles"]:
            if target_role.lower() == role.lower():
                result.append(course)
                break

    return result


def get_free_courses():
    """Return all free courses."""
    return [
        course for course in courses
        if course["type"].lower() == "free"
    ]


def get_paid_courses():
    """Return all paid courses."""
    return [
        course for course in courses
        if course["type"].lower() == "paid"
    ]